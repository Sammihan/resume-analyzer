from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
)

from reportlab.lib.styles import getSampleStyleSheet


def generate_pdf_report(result, output_path="Resume_Analysis_Report.pdf"):

    doc = SimpleDocTemplate(output_path)

    styles = getSampleStyleSheet()

    story = []

    # -------------------------------
    # Title
    # -------------------------------

    story.append(Paragraph("<b>AI Resume Analysis Report</b>", styles["Title"]))

    story.append(Spacer(1, 20))

    # -------------------------------
    # Semantic Match
    # -------------------------------

    story.append(Paragraph("<b>Semantic Match</b>", styles["Heading2"]))

    story.append(
        Paragraph(
            f"{result['semantic_match']:.2f}%",
            styles["BodyText"],
        )
    )

    story.append(Spacer(1, 15))
    # -------------------------------
    # ATS Score
    # -------------------------------

    story.append(Paragraph("<b>ATS Score</b>", styles["Heading2"]))

    story.append(
        Paragraph(
            f"{result['ats_score']:.2f}/100",
            styles["BodyText"],
        )
    )

    story.append(Spacer(1, 15))
    # -------------------------------
    # Missing Skills
    # -------------------------------

    story.append(Paragraph("<b>Missing Skills</b>", styles["Heading2"]))

    for skill in result["missing_skills"]:

        story.append(Paragraph(f"• {skill}", styles["BodyText"]))

    story.append(Spacer(1, 15))

    # -------------------------------
    # AI Suggestions
    # -------------------------------

    story.append(Paragraph("<b>AI Suggestions</b>", styles["Heading2"]))

    story.append(
        Paragraph(
            result["suggestions"].replace("\n", "<br/>"),
            styles["BodyText"],
        )
    )

    story.append(Spacer(1, 20))

    # -------------------------------
    # Footer
    # -------------------------------

    story.append(
        Paragraph(
            "Generated by AI Resume Analyzer",
            styles["Italic"],
        )
    )

    doc.build(story)

    return output_path
